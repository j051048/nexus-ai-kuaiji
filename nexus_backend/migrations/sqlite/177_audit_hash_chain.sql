-- OPT03-B: per-firm audit hash chain for SQLite.
ALTER TABLE audit_events ADD COLUMN prev_hash TEXT;
ALTER TABLE audit_events ADD COLUMN row_hash TEXT;

-- The append-only update guard must be lifted only for this migration's
-- backfill; deletion remains blocked throughout.
DROP TRIGGER audit_events_append_only_update;

WITH RECURSIVE ordered AS (
 SELECT id,firm_id,book_id,company_id,user_id,action,object_id,details,created_at,
  ROW_NUMBER() OVER (PARTITION BY firm_id ORDER BY id) AS rn
 FROM audit_events
), chained(id,firm_id,prev_hash,row_hash,rn) AS (
 SELECT id,firm_id,'',
  accounting_sha256(json_array('',id,firm_id,book_id,company_id,user_id,action,object_id,details,created_at)),rn
 FROM ordered WHERE rn=1
 UNION ALL
 SELECT o.id,o.firm_id,c.row_hash,
  accounting_sha256(json_array(c.row_hash,o.id,o.firm_id,o.book_id,o.company_id,o.user_id,o.action,o.object_id,o.details,o.created_at)),o.rn
 FROM ordered o JOIN chained c ON c.firm_id=o.firm_id AND c.rn+1=o.rn
)
UPDATE audit_events AS a SET prev_hash=c.prev_hash,row_hash=c.row_hash
FROM chained c WHERE a.id=c.id;

CREATE TRIGGER audit_events_hash_insert_guard
BEFORE INSERT ON audit_events
WHEN NEW.prev_hash IS NOT NULL OR NEW.row_hash IS NOT NULL
BEGIN
 SELECT RAISE(ABORT,'audit_events hash is generated by the database');
END;

CREATE TRIGGER audit_events_chain_insert
AFTER INSERT ON audit_events
BEGIN
 UPDATE audit_events SET
  prev_hash=COALESCE((SELECT row_hash FROM audit_events WHERE firm_id=NEW.firm_id AND id<NEW.id ORDER BY id DESC LIMIT 1),''),
  row_hash=accounting_sha256(json_array(
   COALESCE((SELECT row_hash FROM audit_events WHERE firm_id=NEW.firm_id AND id<NEW.id ORDER BY id DESC LIMIT 1),''),
   NEW.id,NEW.firm_id,NEW.book_id,NEW.company_id,NEW.user_id,NEW.action,NEW.object_id,NEW.details,NEW.created_at))
 WHERE id=NEW.id AND row_hash IS NULL;
END;

-- Recreate the append-only update guard, allowing exactly one database-driven
-- initialization update that preserves every content field and matches the
-- expected previous hash and canonical row hash.
CREATE TRIGGER audit_events_append_only_update
BEFORE UPDATE ON audit_events
WHEN NOT (
 OLD.row_hash IS NULL AND NEW.row_hash IS NOT NULL
 AND NEW.id=OLD.id AND NEW.firm_id=OLD.firm_id
 AND NEW.book_id IS OLD.book_id AND NEW.company_id IS OLD.company_id
 AND NEW.user_id=OLD.user_id AND NEW.action=OLD.action
 AND NEW.object_id=OLD.object_id AND NEW.details=OLD.details
 AND NEW.created_at=OLD.created_at
 AND NEW.prev_hash=COALESCE((SELECT row_hash FROM audit_events WHERE firm_id=OLD.firm_id AND id<OLD.id ORDER BY id DESC LIMIT 1),'')
 AND NEW.row_hash=accounting_sha256(json_array(COALESCE(NEW.prev_hash,''),NEW.id,NEW.firm_id,NEW.book_id,NEW.company_id,NEW.user_id,NEW.action,NEW.object_id,NEW.details,NEW.created_at))
)
BEGIN
 SELECT RAISE(ABORT,'audit_events are append-only');
END;
