 WITH CHECK(accounting.firm_manager(firm_id) OR (user_id=accounting.actor_user() AND role='owner' AND accounting.first_owner(firm_id)));
CREATE POLICY memberships_update ON accounting.memberships FOR UPDATE TO accounting_app
 USING(accounting.firm_manager(firm_id)) WITH CHECK(accounting.firm_manager(firm_id));
CREATE POLICY memberships_delete ON accounting.memberships FOR DELETE TO accounting_app USING(accounting.firm_manager(firm_id));
CREATE POLICY companies_read ON accounting.companies FOR SELECT TO accounting_app USING(accounting.company_visible(id));
CREATE POLICY companies_create ON accounting.companies FOR INSERT TO accounting_app WITH CHECK(accounting.firm_manager(accounting.actor_firm()));
CREATE POLICY companies_update ON accounting.companies FOR UPDATE TO accounting_app
 USING(accounting.company_manager(id)) WITH CHECK(accounting.company_manager(id));
CREATE POLICY clients_read ON accounting.firm_clients FOR SELECT TO accounting_app
 USING((firm_id=accounting.actor_firm() OR accounting.actor_firm()='') AND accounting.firm_visible(firm_id));
CREATE POLICY clients_create ON accounting.firm_clients FOR INSERT TO accounting_app WITH CHECK(accounting.firm_manager(firm_id));
CREATE POLICY clients_update ON accounting.firm_clients FOR UPDATE TO accounting_app
 USING(accounting.firm_manager(firm_id)) WITH CHECK(accounting.firm_manager(firm_id));
CREATE POLICY books_read ON accounting.books FOR SELECT TO accounting_app USING(accounting.book_allowed(id));
CREATE POLICY books_create ON accounting.books FOR INSERT TO accounting_app
 WITH CHECK(firm_id=accounting.actor_firm() AND accounting.company_manager(company_id));
CREATE POLICY books_update ON accounting.books FOR UPDATE TO accounting_app
 USING(accounting.book_manager(id)) WITH CHECK(firm_id=accounting.actor_firm() AND accounting.company_manager(company_id));
CREATE POLICY grants_read ON accounting.book_access FOR SELECT TO accounting_app
 USING((user_id=accounting.actor_user() AND firm_id=accounting.actor_firm() AND accounting.book_allowed(book_id)) OR accounting.book_manager(book_id));
CREATE POLICY grants_create ON accounting.book_access FOR INSERT TO accounting_app
 WITH CHECK(firm_id=accounting.actor_firm() AND accounting.book_manager(book_id));
CREATE POLICY grants_update ON accounting.book_access FOR UPDATE TO accounting_app
 USING(accounting.book_manager(book_id)) WITH CHECK(firm_id=accounting.actor_firm() AND accounting.book_manager(book_id));
CREATE POLICY grants_delete ON accounting.book_access FOR DELETE TO accounting_app USING(accounting.book_manager(book_id));
CREATE POLICY departments_read ON accounting.departments FOR SELECT TO accounting_app USING(accounting.company_visible(company_id));
CREATE POLICY departments_create ON accounting.departments FOR INSERT TO accounting_app WITH CHECK(accounting.company_manager(company_id));
CREATE POLICY departments_update ON accounting.departments FOR UPDATE TO accounting_app
 USING(accounting.company_manager(company_id)) WITH CHECK(accounting.company_manager(company_id));
CREATE POLICY company_members_read ON accounting.company_memberships FOR SELECT TO accounting_app
 USING((user_id=accounting.actor_user() AND accounting.actor_active()) OR accounting.company_manager(company_id));
CREATE POLICY company_members_create ON accounting.company_memberships FOR INSERT TO accounting_app WITH CHECK(accounting.company_manager(company_id));
CREATE POLICY company_members_update ON accounting.company_memberships FOR UPDATE TO accounting_app
 USING(accounting.company_manager(company_id)) WITH CHECK(accounting.company_manager(company_id));
CREATE POLICY company_members_delete ON accounting.company_memberships FOR DELETE TO accounting_app USING(accounting.company_manager(company_id));
