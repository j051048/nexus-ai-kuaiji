GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA accounting TO accounting_app;
GRANT SELECT ON accounting.users TO accounting_app;
GRANT SELECT,INSERT,UPDATE ON accounting.users TO accounting_system;
GRANT SELECT,INSERT,UPDATE,DELETE ON accounting.firms,accounting.memberships,accounting.companies,
 accounting.firm_clients,accounting.books,accounting.book_access,accounting.departments,
 accounting.company_memberships,accounting.periods,accounting.accounts,accounting.sources,
 accounting.drafts,accounting.source_evidence,accounting.draft_lines,accounting.exports TO accounting_app;
GRANT SELECT,INSERT ON accounting.audit_events TO accounting_app;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA accounting TO accounting_app;

DO $$ DECLARE item RECORD; BEGIN
 FOR item IN SELECT tablename FROM pg_tables WHERE schemaname='accounting' LOOP
  EXECUTE format('ALTER TABLE accounting.%I ENABLE ROW LEVEL SECURITY',item.tablename);
  EXECUTE format('ALTER TABLE accounting.%I FORCE ROW LEVEL SECURITY',item.tablename);
 END LOOP;
END $$;
