-- Execute only with an administrator carrying BYPASSRLS. No login secrets.
CREATE SCHEMA IF NOT EXISTS accounting;
REVOKE ALL ON SCHEMA accounting FROM PUBLIC;
DO $$ BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='accounting_app') THEN
  CREATE ROLE accounting_app NOLOGIN NOSUPERUSER NOBYPASSRLS;
 END IF;
 IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='accounting_system') THEN
  CREATE ROLE accounting_system NOLOGIN NOSUPERUSER NOBYPASSRLS;
 END IF;
 IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname IN ('accounting_app','accounting_system') AND (rolsuper OR rolbypassrls OR rolcanlogin)) THEN
  RAISE EXCEPTION 'accounting runtime roles must be NOLOGIN NOSUPERUSER NOBYPASSRLS';
 END IF;
END $$;
GRANT USAGE ON SCHEMA accounting TO accounting_app,accounting_system;

CREATE TABLE accounting.users (
 id TEXT PRIMARY KEY,name TEXT NOT NULL,active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1)),
 email TEXT NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX idx_users_email ON accounting.users(lower(email)) WHERE email<>'';
CREATE TABLE accounting.firms (
 id TEXT PRIMARY KEY,name TEXT NOT NULL,created_by TEXT REFERENCES accounting.users(id)
);
CREATE TABLE accounting.memberships (
 firm_id TEXT NOT NULL REFERENCES accounting.firms(id),user_id TEXT NOT NULL REFERENCES accounting.users(id),
 role TEXT NOT NULL CHECK(role IN ('owner','admin','operator','reviewer','viewer')),PRIMARY KEY(firm_id,user_id)
);
CREATE TABLE accounting.companies (id TEXT PRIMARY KEY,name TEXT NOT NULL,tax_id TEXT NOT NULL DEFAULT '');
CREATE UNIQUE INDEX idx_companies_tax_id ON accounting.companies(tax_id) WHERE tax_id<>'';
CREATE TABLE accounting.firm_clients (
 firm_id TEXT NOT NULL REFERENCES accounting.firms(id),company_id TEXT NOT NULL REFERENCES accounting.companies(id),
 status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active','suspended')),PRIMARY KEY(firm_id,company_id)
);
CREATE TABLE accounting.books (
 id TEXT PRIMARY KEY,firm_id TEXT NOT NULL REFERENCES accounting.firms(id),company_id TEXT NOT NULL,
 name TEXT NOT NULL,period TEXT NOT NULL,UNIQUE(id,firm_id),
 FOREIGN KEY(firm_id,company_id) REFERENCES accounting.firm_clients(firm_id,company_id)
);
CREATE TABLE accounting.book_access (
 book_id TEXT NOT NULL,firm_id TEXT NOT NULL,user_id TEXT NOT NULL REFERENCES accounting.users(id),
 role TEXT NOT NULL DEFAULT 'reviewer' CHECK(role IN ('editor','reviewer','viewer')),PRIMARY KEY(book_id,user_id),
 FOREIGN KEY(book_id,firm_id) REFERENCES accounting.books(id,firm_id)
);
CREATE TABLE accounting.departments (
 id TEXT PRIMARY KEY,company_id TEXT NOT NULL REFERENCES accounting.companies(id),name TEXT NOT NULL,UNIQUE(id,company_id)
);
CREATE TABLE accounting.company_memberships (
 company_id TEXT NOT NULL REFERENCES accounting.companies(id),user_id TEXT NOT NULL REFERENCES accounting.users(id),
 role TEXT NOT NULL CHECK(role IN ('owner','admin','finance','employee')),department_id TEXT,
 PRIMARY KEY(company_id,user_id),FOREIGN KEY(department_id,company_id) REFERENCES accounting.departments(id,company_id)
);
CREATE TABLE accounting.periods (
 book_id TEXT NOT NULL REFERENCES accounting.books(id),period TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'open' CHECK(status IN ('open','closed')),PRIMARY KEY(book_id,period)
);
CREATE TABLE accounting.accounts (
 book_id TEXT NOT NULL REFERENCES accounting.books(id),code TEXT NOT NULL,name TEXT NOT NULL,
 active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1)),PRIMARY KEY(book_id,code)
);
CREATE TABLE accounting.sources (
 id TEXT PRIMARY KEY,book_id TEXT NOT NULL REFERENCES accounting.books(id),external_id TEXT NOT NULL,
 source_name TEXT NOT NULL,date TEXT NOT NULL,description TEXT NOT NULL,counterparty TEXT NOT NULL,
 amount_cents BIGINT NOT NULL CHECK(amount_cents>0),direction TEXT NOT NULL CHECK(direction IN ('expense','income')),
 evidence_ref TEXT NOT NULL,fingerprint TEXT NOT NULL,UNIQUE(book_id,external_id),UNIQUE(id,book_id)
);
CREATE TABLE accounting.drafts (
 id TEXT PRIMARY KEY,book_id TEXT NOT NULL REFERENCES accounting.books(id),source_id TEXT NOT NULL UNIQUE,
 description TEXT NOT NULL,status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','approved','exported')),
 version INTEGER NOT NULL DEFAULT 1 CHECK(version>0),explanation TEXT NOT NULL,
 approved_by TEXT REFERENCES accounting.users(id),approved_at TEXT,exported_at TEXT,
 FOREIGN KEY(source_id,book_id) REFERENCES accounting.sources(id,book_id),UNIQUE(id,book_id)
);
CREATE TABLE accounting.source_evidence (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,source_id TEXT NOT NULL,book_id TEXT NOT NULL,
 evidence_ref TEXT NOT NULL,created_at TEXT NOT NULL,created_by TEXT NOT NULL REFERENCES accounting.users(id),
 FOREIGN KEY(source_id,book_id) REFERENCES accounting.sources(id,book_id)
);
CREATE TABLE accounting.draft_lines (
 draft_id TEXT NOT NULL,book_id TEXT NOT NULL,ordinal INTEGER NOT NULL,account_code TEXT NOT NULL,
 debit_cents BIGINT NOT NULL CHECK(debit_cents>=0),credit_cents BIGINT NOT NULL CHECK(credit_cents>=0),
 PRIMARY KEY(draft_id,ordinal),FOREIGN KEY(draft_id,book_id) REFERENCES accounting.drafts(id,book_id),
 FOREIGN KEY(book_id,account_code) REFERENCES accounting.accounts(book_id,code)
);
CREATE TABLE accounting.exports (
 id TEXT PRIMARY KEY,book_id TEXT NOT NULL REFERENCES accounting.books(id),idempotency_key TEXT NOT NULL,
 request_fingerprint TEXT NOT NULL,csv TEXT NOT NULL,count INTEGER NOT NULL,filename TEXT NOT NULL,
 created_at TEXT NOT NULL,created_by TEXT NOT NULL REFERENCES accounting.users(id),UNIQUE(book_id,idempotency_key)
);
CREATE TABLE accounting.audit_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,firm_id TEXT NOT NULL REFERENCES accounting.firms(id),
 book_id TEXT REFERENCES accounting.books(id),user_id TEXT NOT NULL REFERENCES accounting.users(id),
 action TEXT NOT NULL,object_id TEXT NOT NULL,details TEXT NOT NULL,created_at TEXT NOT NULL
);
CREATE INDEX idx_sources_book ON accounting.sources(book_id,date);
CREATE INDEX idx_drafts_book ON accounting.drafts(book_id,status);
CREATE INDEX idx_audit_book ON accounting.audit_events(book_id,id);
CREATE INDEX idx_evidence_source ON accounting.source_evidence(book_id,source_id,id);
CREATE INDEX idx_book_access_user ON accounting.book_access(user_id,firm_id);
CREATE INDEX idx_books_company ON accounting.books(firm_id,company_id);
CREATE INDEX idx_company_memberships_user ON accounting.company_memberships(user_id,company_id);

-- Identity settings are supplied only by the backend after authentication.
-- Fixed search_path plus an owner carrying BYPASSRLS avoid recursive policies.
CREATE FUNCTION accounting.actor_user() RETURNS TEXT LANGUAGE sql STABLE
 SET search_path=pg_catalog AS $$ SELECT coalesce(current_setting('app.user_id',true),'') $$;
CREATE FUNCTION accounting.actor_firm() RETURNS TEXT LANGUAGE sql STABLE
 SET search_path=pg_catalog AS $$ SELECT coalesce(current_setting('app.firm_id',true),'') $$;
CREATE FUNCTION accounting.actor_active() RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER
 SET search_path=pg_catalog,accounting,pg_temp AS $$
 SELECT EXISTS(SELECT 1 FROM accounting.users WHERE id=accounting.actor_user() AND active=1)
$$;
CREATE FUNCTION accounting.firm_role(target TEXT) RETURNS TEXT LANGUAGE sql STABLE SECURITY DEFINER
 SET search_path=pg_catalog,accounting,pg_temp AS $$
 SELECT role FROM accounting.memberships WHERE firm_id=target AND user_id=accounting.actor_user()
 AND accounting.actor_active()
$$;
CREATE FUNCTION accounting.firm_manager(target TEXT) RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER
 SET search_path=pg_catalog,accounting,pg_temp AS $$
 SELECT target=accounting.actor_firm() AND coalesce(accounting.firm_role(target) IN ('owner','admin'),false)
$$;
CREATE FUNCTION accounting.firm_visible(target TEXT) RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER
 SET search_path=pg_catalog,accounting,pg_temp AS $$
 SELECT accounting.actor_active() AND (
  accounting.firm_role(target) IS NOT NULL
  OR EXISTS(SELECT 1 FROM accounting.firms WHERE id=target AND created_by=accounting.actor_user())
  OR EXISTS(SELECT 1 FROM accounting.firm_clients fc JOIN accounting.company_memberships cm ON cm.company_id=fc.company_id
   WHERE fc.firm_id=target AND fc.status='active' AND cm.user_id=accounting.actor_user())
 )
$$;
CREATE FUNCTION accounting.first_owner(target TEXT) RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER
 SET search_path=pg_catalog,accounting,pg_temp AS $$
 SELECT accounting.actor_active()
 AND EXISTS(SELECT 1 FROM accounting.firms WHERE id=target AND created_by=accounting.actor_user())
 AND NOT EXISTS(SELECT 1 FROM accounting.memberships WHERE firm_id=target AND role='owner')
$$;
CREATE FUNCTION accounting.company_visible(target TEXT) RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER
 SET search_path=pg_catalog,accounting,pg_temp AS $$
 SELECT accounting.actor_active() AND (
  EXISTS(SELECT 1 FROM accounting.company_memberships WHERE company_id=target AND user_id=accounting.actor_user())
  OR EXISTS(SELECT 1 FROM accounting.firm_clients fc WHERE fc.company_id=target AND fc.firm_id=accounting.actor_firm()
   AND fc.status='active' AND (
    accounting.firm_manager(fc.firm_id)
    OR (accounting.firm_role(fc.firm_id) IS NOT NULL AND EXISTS(
     SELECT 1 FROM accounting.books b JOIN accounting.book_access ba ON ba.book_id=b.id AND ba.firm_id=b.firm_id
     WHERE b.company_id=target AND b.firm_id=fc.firm_id AND ba.user_id=accounting.actor_user()))
   ))
 )
$$;
CREATE FUNCTION accounting.company_manager(target TEXT) RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER
 SET search_path=pg_catalog,accounting,pg_temp AS $$
 SELECT accounting.actor_active() AND EXISTS(SELECT 1 FROM accounting.firm_clients fc
 WHERE fc.company_id=target AND fc.firm_id=accounting.actor_firm() AND fc.status='active'
 AND (accounting.firm_manager(fc.firm_id) OR EXISTS(SELECT 1 FROM accounting.company_memberships cm
 WHERE cm.company_id=target AND cm.user_id=accounting.actor_user() AND cm.role IN ('owner','admin'))))
$$;
CREATE FUNCTION accounting.user_visible(target TEXT) RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER
 SET search_path=pg_catalog,accounting,pg_temp AS $$
 SELECT target=accounting.actor_user() OR (accounting.actor_active() AND (
  accounting.firm_manager(accounting.actor_firm()) OR EXISTS(
   SELECT 1 FROM accounting.company_memberships cm JOIN accounting.firm_clients fc ON fc.company_id=cm.company_id
   WHERE cm.user_id=accounting.actor_user() AND cm.role IN ('owner','admin')
   AND fc.firm_id=accounting.actor_firm() AND fc.status='active')
 ))
$$;
CREATE FUNCTION accounting.book_allowed(target TEXT,write_access BOOLEAN DEFAULT false) RETURNS BOOLEAN
 LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,accounting,pg_temp AS $$
 SELECT accounting.actor_active() AND EXISTS(
  SELECT 1 FROM accounting.books b JOIN accounting.firm_clients fc ON fc.firm_id=b.firm_id AND fc.company_id=b.company_id
  WHERE b.id=target AND b.firm_id=accounting.actor_firm() AND fc.status='active' AND (
   accounting.firm_manager(b.firm_id) OR EXISTS(
    SELECT 1 FROM accounting.book_access ba WHERE ba.book_id=b.id AND ba.firm_id=b.firm_id
    AND ba.user_id=accounting.actor_user() AND (
     (accounting.firm_role(b.firm_id) IS NOT NULL AND (
      NOT write_access OR (ba.role IN ('editor','reviewer') AND accounting.firm_role(b.firm_id) IN ('operator','reviewer'))))
     OR (accounting.firm_role(b.firm_id) IS NULL AND EXISTS(
      SELECT 1 FROM accounting.company_memberships cm WHERE cm.company_id=b.company_id
      AND cm.user_id=accounting.actor_user() AND cm.role IN ('owner','admin','finance')
      AND (NOT write_access OR ba.role IN ('editor','reviewer'))))
    )
   )
  )
 )
$$;
CREATE FUNCTION accounting.book_manager(target TEXT) RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER
 SET search_path=pg_catalog,accounting,pg_temp AS $$
 SELECT EXISTS(SELECT 1 FROM accounting.books b WHERE b.id=target AND b.firm_id=accounting.actor_firm()
 AND accounting.company_manager(b.company_id))
$$;

