 WITH CHECK(created_by=accounting.actor_user() AND accounting.actor_active());
CREATE POLICY firms_update ON accounting.firms FOR UPDATE TO accounting_app
 USING(accounting.firm_manager(id)) WITH CHECK(accounting.firm_manager(id));
