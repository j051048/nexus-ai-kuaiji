-- Only draft replacement requires DELETE. Source evidence and export receipts
-- have no DELETE policy; audit has neither UPDATE nor DELETE privileges.
CREATE POLICY lines_delete ON accounting.draft_lines FOR DELETE TO accounting_app USING(accounting.book_allowed(book_id,true));
CREATE POLICY audit_read ON accounting.audit_events FOR SELECT TO accounting_app
 USING(firm_id=accounting.actor_firm() AND (accounting.firm_manager(firm_id) OR accounting.book_allowed(book_id) OR (book_id IS NULL AND user_id=accounting.actor_user())));
CREATE POLICY audit_append ON accounting.audit_events FOR INSERT TO accounting_app
 WITH CHECK(user_id=accounting.actor_user() AND firm_id=accounting.actor_firm() AND accounting.actor_active()
 AND (book_id IS NULL OR accounting.book_allowed(book_id)));

-- Supabase browser roles must never access this backend-owned schema, even
-- when the project exposes another schema via PostgREST.
DO $$ DECLARE browser_role TEXT; BEGIN
 FOREACH browser_role IN ARRAY ARRAY['anon','authenticated'] LOOP
  IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname=browser_role) THEN
   EXECUTE format('REVOKE ALL ON SCHEMA accounting FROM %I',browser_role);
   EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA accounting FROM %I',browser_role);
   EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA accounting FROM %I',browser_role);
   EXECUTE format('REVOKE ALL ON ALL FUNCTIONS IN SCHEMA accounting FROM %I',browser_role);
  END IF;
 END LOOP;
END $$;
