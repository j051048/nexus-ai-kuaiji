"""PLT06-D: a restored copy stays isolated until audited, then finishes one deal.

The drill is deliberately end-to-end and local (SQLite): take an encrypted
backup of a live book, restore it into a brand-new database, prove the restored
copy refuses to serve or send anything while the hold is on, release the hold
through an audited write, then complete one real business step (import → review →
export) and confirm the restored copy never starts serving, sending or background work on
its own. The pre-crash `unknown` notification rule is asserted by the notification
fencing suite (``test_n03_notification_fencing``); this drill keeps the hold and
release path honest on its own.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.accounting.database import Database  # noqa: E402
from types import SimpleNamespace  # noqa: E402

from app.accounting.directory import DirectoryService  # noqa: E402
from app.accounting.models import (  # noqa: E402
    ApprovalRequest,
    ExportRequest,
    ImportRequest,
)
from app.accounting.domain import Actor  # noqa: E402
from app.accounting.service import AccountingError, AccountingService  # noqa: E402
from app.delivery.notification_dispatch import assert_not_held  # noqa: E402
from scripts import backup_accounting as backup_tool  # noqa: E402
from test_directory import case as directory_case  # noqa: F401
from review_policy_fixtures import ensure_independent_reviewer  # noqa: E402


MARKERS = ("restore-verification.json", "restore-hold.json")


def _release_hold(db_path: str, firm_id: str, book_id: str, actor_user: str, reason: str) -> None:
    directory = Path(db_path).parent
    removed = [name for name in MARKERS if (directory / name).is_file()]
    assert removed, "restore must plant a marker the operator has to clear"
    for name in removed:
        (directory / name).unlink()
    database = Database(Path(db_path))
    with database.transaction(write=True) as conn:
        updated = conn.execute(
            "UPDATE restore_state SET hold=0,reason=?,updated_by=?,updated_at=? "
            "WHERE instance_id='restored'",
            (reason, actor_user, "2026-11-17T00:00:00+00:00"),
        ).rowcount
        assert updated == 1
        # Releasing the hold is itself an audited act: append the row through the
        # same chained audit table (hashes are generated by the database).
        conn.execute(
            "INSERT INTO audit_events(firm_id,book_id,user_id,action,object_id,details,created_at) "
            "VALUES(?,?,?,'recovery.restore_released',?,?,?)",
            (
                firm_id,
                book_id,
                actor_user,
                "restored",
                '{"reason": "恢复核对完成"}',
                "2026-11-17T00:00:00+00:00",
            ),
        )


def test_restored_copy_is_held_then_released_and_finishes_one_deal(directory_case, tmp_path):
    c = directory_case
    book = c.book["id"]
    reviewer = ensure_independent_reviewer(c.db, c.actor, book)
    storage = tmp_path / "storage"
    storage.mkdir()
    backup_dir = tmp_path / "backup"
    backup_tool.backup(str(c.db.path), str(storage), str(backup_dir))

    restored_dir = tmp_path / "restored"
    receipt = backup_tool.restore(str(backup_dir), str(restored_dir))
    restored_path = restored_dir / "database.sqlite"
    # A restore never resumes serving, sending or background work on its own.
    assert receipt["serving_enabled"] is False
    assert receipt["outbound_disabled"] is True
    assert receipt["worker_autostart"] is False
    assert receipt["in_flight_jobs_hold"] is True

    restored = Database(restored_path)
    # Startup fails closed while the hold is on; serving cannot be silently enabled.
    with pytest.raises(SystemExit) as error:
        restored.assert_restore_hold()
    assert "恢复" in str(error.value)

    with restored.transaction(actor=c.actor) as conn:
        with pytest.raises(AccountingError) as held:
            assert_not_held(conn, restored)
        assert held.value.status == 409

    _release_hold(str(restored_path), c.actor.firm_id, book, c.actor.user_id, "恢复核对完成，解除隔离")

    restored = Database(restored_path)
    restored.assert_restore_hold()
    with restored.transaction(actor=c.actor) as conn:
        assert_not_held(conn, restored)
        released = conn.execute(
            "SELECT user_id,action FROM audit_events WHERE action='recovery.restore_released'"
        ).fetchone()
    assert released["user_id"] == c.actor.user_id

    # Permission matrix on the restored copy still separates writer from reviewer.
    service = AccountingService(restored)
    directory = DirectoryService(restored)
    assert service.workbench(c.actor)["books"]
    # A person who exists but was never granted this book sees nothing.
    stranger = SimpleNamespace(
        user_id="post-restore-stranger",
        display_name="外部人",
        email="stranger@example.test",
    )
    directory.register_identity(stranger)
    stranger_actor = Actor(stranger.user_id, c.actor.firm_id)
    with pytest.raises(AccountingError) as denied:
        service.get_book(stranger_actor, book)
    assert denied.value.status in (403, 404)

    # One real deal completes end to end on the restored copy.
    service.import_sources(
        c.actor,
        book,
        ImportRequest(
            source_name="恢复后新业务",
            rows=[
                {
                    "external_id": "post-restore-1",
                    "date": "2026-10-02",
                    "description": "恢复后办公用品",
                    "amount": "20.00",
                    "direction": "expense",
                    "evidence_ref": "恢复后测试发票",
                }
            ],
        ),
    )
    service.suggestions(c.actor, book)
    drafts = service.get_book(c.actor, book)["drafts"]
    assert drafts, "restored copy must be able to generate a draft after release"
    draft = drafts[-1]
    service.approve(
        reviewer,
        book,
        draft["id"],
        ApprovalRequest(expected_version=draft["version"]),
    )
    receipt_export = service.export(
        c.actor,
        book,
        ExportRequest(draft_ids=[draft["id"]], idempotency_key="plt06-restored-export"),
    )
    assert receipt_export["csv"]
