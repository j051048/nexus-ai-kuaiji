import { openAccounting, openBookTools } from './ui-navigation';
import { expect, test } from '@playwright/test';

test('第七阶段真实客户配置：科目预览导入、固定模板演算与版本修订', async ({ page, request }) => {
  const session = await (await request.get('/api/session?persona=accountant')).json();
  const headers = { Authorization: `Bearer ${session.token}` };
  const created = await request.post('/api/books', { headers, data: { name: '第七阶段配置验证（虚构企业）', period: '2026-10' } });
  expect(created.status()).toBe(201); const book = await created.json();
  await page.goto('/');
  await openAccounting(page); await page.getByLabel('搜索企业名称').fill('第七阶段配置验证');
  await page.getByRole('listitem').filter({ hasText: book.name }).click();
  await openBookTools(page); await page.getByRole('button', { name: '科目与模板', exact: true }).click();
  await expect(page.getByRole('heading', { name: '把企业的账，配置清楚。', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '导入 / 维护科目', exact: true }).click();
  const chartDialog = page.getByRole('dialog', { name: '维护客户科目', exact: true });
  await chartDialog.getByLabel('科目配置 JSON', { exact: true }).fill(JSON.stringify([{ code: '6401.01', name: '试点企业服务成本', category: 'cost', normal_balance: 'debit', active: true, auxiliary_requirements: ['counterparty'] }]));
  await expect(chartDialog.getByRole('button', { name: '保存配置', exact: true })).toBeDisabled();
  await chartDialog.getByRole('button', { name: '预览整批科目', exact: true }).click();
  await expect(chartDialog.getByText('整批有效：新增 1 项，更新 0 项。保存时再次核对权限、期间与版本。', { exact: true })).toBeVisible();
  const before = await (await request.get(`/api/books/${book.id}/catalog`, { headers })).json();
  expect(before.accounts.some((item: { code: string }) => item.code === '6401.01')).toBe(false);
  await chartDialog.getByRole('button', { name: '保存配置', exact: true }).click();
  await expect(chartDialog).toHaveCount(0);
  const accountRow = page.getByRole('row').filter({ hasText: '6401.01' });
  await expect(accountRow).toContainText('试点企业服务成本');
  await expect(accountRow).toContainText('交易对方');

  await page.getByRole('button', { name: '配置模板', exact: true }).click();
  const templateDialog = page.getByRole('dialog', { name: '配置固定记账模板', exact: true });
  const definition = { name: '试点企业采购服务费用', business_type: 'procurement_expense', direction: 'expense', category: 'office', payment_status: 'paid', active: true,
    lines: [{ account_code: '6401.01', side: 'debit', amount_field: 'gross' }, { account_code: '1002', side: 'credit', amount_field: 'gross' }] };
  await templateDialog.getByLabel('模板配置 JSON', { exact: true }).fill(JSON.stringify(definition));
  await templateDialog.getByRole('button', { name: '演算示例', exact: true }).click();
  await expect(templateDialog.getByText('借 113.00 / 贷 0.00', { exact: true })).toBeVisible();
  await templateDialog.getByRole('button', { name: '保存配置', exact: true }).click();
  await expect(templateDialog).toHaveCount(0);
  await expect(page.getByText('试点企业采购服务费用', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '查看并修订模板', exact: true }).click();
  await templateDialog.getByLabel('模板配置 JSON', { exact: true }).fill(JSON.stringify({ ...definition, name: '试点企业采购服务费用（第二版）' }));
  await templateDialog.getByRole('button', { name: '保存配置', exact: true }).click();
  await expect(templateDialog).toHaveCount(0);
  const saved = await (await request.get(`/api/books/${book.id}/catalog`, { headers })).json();
  expect(saved.templates).toHaveLength(1); expect(saved.templates[0].version).toBe(2);
  await page.screenshot({ path: 'artifacts/stage7-catalog-mvp.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.screenshot({ path: 'artifacts/stage7-client-catalog.png', fullPage: true });
});

test('第七阶段真实分页与辅助核算：二十五笔待办按需读取，缺辅助值阻断审核', async ({ page, request }) => {
  const session = await (await request.get('/api/session?persona=accountant')).json();
  const headers = { Authorization: `Bearer ${session.token}` };
  const created = await request.post('/api/books', { headers, data: { name: '第七阶段分页验证（虚构企业）', period: '2026-10' } });
  expect(created.status()).toBe(201); const book = await created.json();
  const account = await request.post(`/api/books/${book.id}/catalog/accounts`, { headers, data: { code: '6401.02', name: '有项目核算的成本', category: 'cost', normal_balance: 'debit', active: true, auxiliary_requirements: ['project'] } });
  expect(account.status()).toBe(201);
  const rows = Array.from({ length: 25 }, (_, index) => ({ external_id: `stage7-page:${index}`, date: '2026-10-01', description: `办公用品分页验证 ${String(index + 1).padStart(2, '0')}`, counterparty: '虚构供应商', amount: '113.00', direction: 'expense', evidence_ref: `归档票据-${index}` }));
  const imported = await request.post(`/api/books/${book.id}/imports`, { headers, data: { source_name: '第七阶段虚构流水验证', rows } });
  expect(imported.status()).toBe(200);
  const suggestions = await request.post(`/api/books/${book.id}/suggestions`, { headers });
  expect(suggestions.status()).toBe(200); expect((await suggestions.json()).created).toBe(25);
  await page.goto('/');
  await openAccounting(page); await page.getByLabel('搜索企业名称').fill('第七阶段分页验证');
  await page.getByRole('listitem').filter({ hasText: book.name }).click();
  const pagination = page.getByLabel('凭证待办分页', { exact: true });
  await expect(pagination).toContainText('共 25 项 · 第 1 页');
  await expect(page.getByRole('button', { name: /^复核 办公用品分页验证/ })).toHaveCount(20);
  await pagination.getByRole('button', { name: '下一页', exact: true }).click();
  await expect(pagination).toContainText('第 2 页');
  await expect(page.getByRole('button', { name: /^复核 办公用品分页验证/ })).toHaveCount(5);
  await page.getByRole('button', { name: /^复核 办公用品分页验证/ }).first().click();
  await page.getByLabel('第 1 行会计科目', { exact: true }).selectOption('6401.02');
  await expect(page.getByLabel('第 1 行project辅助核算', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '保存草稿', exact: true }).click();
  await expect(page.getByLabel('待处理问题', { exact: true })).toContainText('项目');
  await expect(page.getByRole('button', { name: '确认审核', exact: true })).toBeDisabled();
  await page.getByLabel('第 1 行project辅助核算', { exact: true }).fill('MVP 验证项目');
  await page.getByRole('button', { name: '保存草稿', exact: true }).click();
  await expect(page.getByRole('button', { name: '确认审核', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: '确认审核', exact: true }).click();
  await expect(page.getByLabel('第 1 行project辅助核算', { exact: true })).toBeDisabled();
});

test('第七阶段真实关闭期间：配置只读，科目与模板 API 不能写入', async ({ page, request }) => {
  const session = await (await request.get('/api/session?persona=accountant')).json();
  const headers = { Authorization: `Bearer ${session.token}` };
  const created = await request.post('/api/books', { headers, data: { name: '第七阶段关闭期间验证（虚构企业）', period: '2026-10' } });
  expect(created.status()).toBe(201); const book = await created.json();
  const oldClose = await request.post(`/api/books/${book.id}/periods/2026-10/close`, { headers }); expect(oldClose.status()).toBe(409);
  const preflight = await request.post(`/api/books/${book.id}/closing/preflights`, { headers, data: { idempotency_key: crypto.randomUUID() } }); expect(preflight.status()).toBe(201);
  const snapshot = await preflight.json(); expect(snapshot.report.passed).toBe(true);
  const reviewed = await request.post(`/api/books/${book.id}/closing/snapshots/${snapshot.id}/review`, { headers, data: { reason: '虚构空账套本期资料及银行流水完整性已核对', materials_confirmed: true } }); expect(reviewed.status()).toBe(200);
  const closed = await request.post(`/api/books/${book.id}/closing/close`, { headers, data: { snapshot_id: snapshot.id, reason: '依据当前复核快照锁定期间' } }); expect(closed.status()).toBe(200);
  const rejected = await request.post(`/api/books/${book.id}/catalog/accounts`, { headers, data: { code: '9999', name: '关闭期间不得建立' } }); expect(rejected.status()).toBe(403);
  await page.goto('/'); await openAccounting(page); await page.getByLabel('搜索企业名称').fill('第七阶段关闭期间验证');
  await page.getByRole('listitem').filter({ hasText: book.name }).click();
  await openBookTools(page); await page.getByRole('button', { name: '科目与模板', exact: true }).click();
  await expect(page.getByRole('heading', { name: '企业科目', exact: false })).toBeVisible();
  await expect(page.getByRole('button', { name: '导入 / 维护科目', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: '配置模板', exact: true })).toHaveCount(0);
});
