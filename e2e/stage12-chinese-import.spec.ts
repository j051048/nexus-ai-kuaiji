import { expect, test } from '@playwright/test';
import { openAccounting } from './ui-navigation';

test('中文流水向导在手机分步确认，保留原件并识别再次导入', async ({ page, request }) => {
  const session = await (await request.get('/api/session?persona=accountant')).json();
  const headers = { Authorization: `Bearer ${session.token}` };
  const name = `第十二阶段中文导入 ${crypto.randomUUID().slice(0, 8)}`;
  const book = await (await request.post('/api/books', { headers, data: { name, period: '2026-10' } })).json();
  const content = '交易编号,交易日期,摘要,交易对方,金额,方向,凭据引用\r\nCN-001,2026/10/01,合成办公采购,虚构文具店,0.30,支出,虚构发票001\r\nCN-002,2026/10/02,合成服务收入,虚构客户甲,10.00,收入,虚构合同002\r\n';
  await page.goto('/');
  await openAccounting(page);
  await page.getByLabel('搜索企业名称').fill(name);
  await page.getByRole('listitem').filter({ hasText: name }).click();
  await page.getByRole('button', { name: '导入流水', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '导入原始流水', exact: true });
  await expect(dialog).toContainText('选择文件与账号');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByLabel('选择银行流水文件').setInputFiles({ name: '中文合成流水.csv', mimeType: 'text/csv', buffer: Buffer.from(content, 'utf8') });
  await expect(dialog).toContainText('2条流水');
  await dialog.getByLabel('银行账号标识（脱敏）', { exact: true }).fill('虚构工商银行-1234');
  await dialog.getByRole('button', { name: '确认字段', exact: true }).click();
  await expect(dialog.getByLabel('对应交易日期')).toHaveValue('1');
  await dialog.getByRole('button', { name: '预览流水', exact: true }).click();
  await expect(dialog).toContainText('新增收入合计');
  await expect(dialog).toContainText('10.00');
  await expect(dialog).toContainText('0.30');
  await expect(dialog.getByRole('button', { name: '确认导入', exact: true })).toBeDisabled();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.screenshot({ path: 'artifacts/stage12-chinese-import-mobile.png', fullPage: false });
  await dialog.getByLabel('我已核对目标企业、月份、账号、字段和收入支出合计', { exact: true }).check();
  await dialog.getByRole('button', { name: '确认导入', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  const detail = await (await request.get(`/api/books/${book.id}`, { headers })).json();
  expect(detail.sources).toHaveLength(2);
  const evidence = await (await request.get(`/api/books/${book.id}/import-wizard/sources/${detail.sources[0].id}/evidence`, { headers })).json();
  expect(evidence.originals[0].filename).toBe('中文合成流水.csv');
  expect((await request.get(`/api/books/${book.id}/import-wizard/files/${evidence.originals[0].file_id}`, { headers })).status()).toBe(200);
  const employee = await (await request.get('/api/session?persona=employee')).json();
  expect((await request.get(`/api/books/${book.id}/import-wizard/files/${evidence.originals[0].file_id}`, { headers: { Authorization: `Bearer ${employee.token}` } })).status()).toBe(404);
  await page.getByRole('button', { name: '导入流水', exact: true }).click();
  await page.getByLabel('选择银行流水文件').setInputFiles({ name: '中文合成流水.csv', mimeType: 'text/csv', buffer: Buffer.from(content, 'utf8') });
  await expect(dialog).toContainText('2条流水');
  await dialog.getByLabel('使用保存的银行格式').selectOption({ label: '虚构工商银行-1234 · bank-statement · v1' });
  await dialog.getByRole('button', { name: '确认字段', exact: true }).click();
  await dialog.getByRole('button', { name: '预览流水', exact: true }).click();
  await expect(dialog).toContainText('重复将跳过');
  await expect(dialog.locator('.import-wizard-row')).toHaveCount(2);
  await expect(dialog.locator('.import-wizard-row').first()).toContainText('重复跳过');
});

test('中文导入是真正覆盖视口的模态向导，锁定背景滚动并恢复 Escape 焦点', async ({ page, request }) => {
  const session = await (await request.get('/api/session?persona=accountant')).json();
  const headers = { Authorization: `Bearer ${session.token}` };
  const name = `合成导入模态验证 ${crypto.randomUUID().slice(0, 8)}`;
  const book = await (await request.post('/api/books', { headers, data: { name, period: '2026-10' } })).json();
  await page.setViewportSize({ width: 1100, height: 700 });
  await page.goto('/'); await openAccounting(page);
  await page.getByLabel('搜索企业名称').fill(name);
  await page.getByRole('listitem').filter({ hasText: name }).click();
  const opener = page.getByRole('button', { name: '导入流水', exact: true });
  const priorOverflow = await page.evaluate(() => ({ body: document.body.style.overflow, document: document.documentElement.style.overflow }));
  await opener.click();
  const dialog = page.getByRole('dialog', { name: '导入原始流水', exact: true });
  const backdrop = page.locator('.import-wizard-backdrop');
  await expect(dialog).toBeVisible();
  expect(await backdrop.evaluate(element => getComputedStyle(element).position)).toBe('fixed');
  expect(await backdrop.evaluate(element => { const rect = element.getBoundingClientRect(); return { x: rect.x, y: rect.y, width: rect.width, height: rect.height }; })).toEqual({ x: 0, y: 0, width: 1100, height: 700 });
  expect(await page.evaluate(() => ({ body: document.body.style.overflow, document: document.documentElement.style.overflow }))).toEqual({ body: 'hidden', document: 'hidden' });
  const backgroundScroll = await page.evaluate(() => window.scrollY);
  await page.mouse.move(5, 5); await page.mouse.wheel(0, 800);
  await dialog.getByRole('button', { name: '取消', exact: true }).focus();
  await page.keyboard.press('Tab');
  await expect(dialog.getByRole('button', { name: '关闭导入向导', exact: true })).toBeFocused();
  expect(await page.evaluate(() => window.scrollY)).toBe(backgroundScroll);
  await page.keyboard.press('Shift+Tab');
  await expect(dialog.getByRole('button', { name: '取消', exact: true })).toBeFocused();
  await dialog.getByLabel('银行账号标识（脱敏）', { exact: true }).focus();
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(opener).toBeFocused();
  expect(await page.evaluate(() => ({ body: document.body.style.overflow, document: document.documentElement.style.overflow }))).toEqual(priorOverflow);

  await page.setViewportSize({ width: 390, height: 844 });
  await opener.click(); await expect(dialog).toBeVisible();
  expect(await dialog.evaluate(element => { const rect = element.getBoundingClientRect(); return { x: rect.x, y: rect.y, width: rect.width, height: rect.height }; })).toEqual({ x: 0, y: 0, width: 390, height: 844 });
  await dialog.locator('summary').filter({ hasText: '或直接粘贴中文' }).click();
  expect(await dialog.locator('.import-wizard-main').evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true);
  await dialog.locator('.import-wizard-main').evaluate(element => { element.scrollTop = 200; });
  expect(await dialog.locator('.import-wizard-main').evaluate(element => element.scrollTop)).toBeGreaterThan(0);
  const footer = await dialog.locator('.import-wizard-footer').boundingBox();
  expect(footer).not.toBeNull();
  expect(footer!.y + footer!.height).toBeLessThanOrEqual(844);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0); await expect(opener).toBeFocused();
  expect(await page.evaluate(() => ({ body: document.body.style.overflow, document: document.documentElement.style.overflow }))).toEqual(priorOverflow);
  expect((await (await request.get(`/api/books/${book.id}`, { headers })).json()).sources).toEqual([]);
});
